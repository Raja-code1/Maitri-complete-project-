"""
Member 5: Geospatial Export Engine (.shp ZIP & .kml)
Converts simulation outputs and inundation polygons into standard ESRI Shapefile packages
(with .shp, .shx, .dbf, .prj) and Google Earth KML files.
"""

import os
import zipfile
import tempfile
from pathlib import Path
from typing import Dict, Any, List
import shapefile
from shapely.geometry import shape, Polygon, MultiPolygon
from jal_drishti.config import EXPORT_DIR

# Standard WGS84 PRJ string
WGS84_PRJ = (
    'GEOGCS["GCS_WGS_1984",'
    'DATUM["D_WGS_1984",'
    'SPHEROID["WGS_1984",6378137.0,298.257223563]],'
    'PRIMEM["Greenwich",0.0],'
    'UNIT["Degree",0.0174532925199433]]'
)

class GeospatialExportEngine:
    """
    Automated generation of OGC-compliant GIS export bundles.
    """

    @staticmethod
    def export_shapefile_zip(
        geojson_data: Dict[str, Any],
        base_filename: str = "dam_break_inundation"
    ) -> Path:
        """
        Creates a valid ESRI Shapefile bundle (.shp, .shx, .dbf, .prj) inside a ZIP archive.
        """
        out_zip_path = EXPORT_DIR / f"{base_filename}_shapefile.zip"

        with tempfile.TemporaryDirectory() as tmp_dir:
            tmp_shp_base = Path(tmp_dir) / base_filename
            
            # Initialize Shapefile Writer (POLYGON)
            w = shapefile.Writer(str(tmp_shp_base), shapeType=shapefile.POLYGON)
            
            # Attributes schema
            w.field("MODEL", "C", size=20)
            w.field("DEPTH_BAND", "C", size=40)
            w.field("MIN_D_M", "F", decimal=2)
            w.field("MAX_D_M", "F", decimal=2)
            w.field("COLOR_HEX", "C", size=10)

            features = geojson_data.get("features", [])
            has_records = False

            for feat in features:
                props = feat.get("properties", {})
                geom = feat.get("geometry", {})
                if not geom:
                    continue

                sh_geom = shape(geom)
                polygons: List[Polygon] = []
                if isinstance(sh_geom, Polygon):
                    polygons = [sh_geom]
                elif isinstance(sh_geom, MultiPolygon):
                    polygons = list(sh_geom.geoms)

                for poly in polygons:
                    # Exterior ring coordinates [lon, lat]
                    coords = list(poly.exterior.coords)
                    # Convert to [lon, lat] list
                    parts = [[[pt[0], pt[1]] for pt in coords]]
                    w.poly(parts)
                    w.record(
                        str(props.get("model", "Delft3D")),
                        str(props.get("depth_band", "Inundation Zone")),
                        float(props.get("min_depth_m", 0.05)),
                        float(props.get("max_depth_m", 1.50)),
                        str(props.get("color", "#dc2626"))
                    )
                    has_records = True

            if not has_records:
                # Add default dummy boundary if empty
                w.poly([[[79.65, 30.45], [79.75, 30.45], [79.75, 30.55], [79.65, 30.55], [79.65, 30.45]]])
                w.record("Delft3D", "Nominal Boundary", 0.05, 1.0, "#dc2626")

            w.close()

            # Write .prj coordinate file
            prj_file = Path(tmp_dir) / f"{base_filename}.prj"
            with open(prj_file, "w", encoding="utf-8") as f:
                f.write(WGS84_PRJ)

            # Package into ZIP
            with zipfile.ZipFile(out_zip_path, "w", zipfile.ZIP_DEFLATED) as zipf:
                for ext in [".shp", ".shx", ".dbf", ".prj"]:
                    fpath = Path(tmp_dir) / f"{base_filename}{ext}"
                    if fpath.exists():
                        zipf.write(fpath, arcname=f"{base_filename}{ext}")

        return out_zip_path

    @staticmethod
    def export_kml(
        geojson_data: Dict[str, Any],
        scenario_title: str = "Dam Break Flood Inundation",
        base_filename: str = "dam_break_inundation"
    ) -> Path:
        """
        Creates a richly styled OGC KML 2.2 file for Google Earth visualization.
        """
        out_kml_path = EXPORT_DIR / f"{base_filename}.kml"

        kml_header = f"""<?xml version="1.0" encoding="UTF-8"?>
<kml xmlns="http://www.opengis.net/kml/2.2">
  <Document>
    <name>{scenario_title}</name>
    <description>Simulated flood inundation contours and impact zones generated by Jal-Drishti Hydrodynamic Modeling Framework (NTRO / SIH 2026).</description>
    
    <Style id="catastrophicStyle">
      <LineStyle><color>ff1d1d7f</color><width>2</width></LineStyle>
      <PolyStyle><color>aa1d1d7f</color><fill>1</fill><outline>1</outline></PolyStyle>
    </Style>
    <Style id="highHazardStyle">
      <LineStyle><color>ff2626dc</color><width>2</width></LineStyle>
      <PolyStyle><color>aa2626dc</color><fill>1</fill><outline>1</outline></PolyStyle>
    </Style>
    <Style id="moderateStyle">
      <LineStyle><color>ff1673f9</color><width>1.5</width></LineStyle>
      <PolyStyle><color>aa1673f9</color><fill>1</fill><outline>1</outline></PolyStyle>
    </Style>
    <Style id="mildStyle">
      <LineStyle><color>fff8bd38</color><width>1</width></LineStyle>
      <PolyStyle><color>88f8bd38</color><fill>1</fill><outline>1</outline></PolyStyle>
    </Style>
    <Style id="sphSurgeStyle">
      <LineStyle><color>ff4444ef</color><width>2</width></LineStyle>
      <PolyStyle><color>774444ef</color><fill>1</fill><outline>1</outline></PolyStyle>
    </Style>
"""

        kml_body = []
        features = geojson_data.get("features", [])

        for idx, feat in enumerate(features):
            props = feat.get("properties", {})
            geom = feat.get("geometry", {})
            if not geom:
                continue

            sh_geom = shape(geom)
            polygons: List[Polygon] = []
            if isinstance(sh_geom, Polygon):
                polygons = [sh_geom]
            elif isinstance(sh_geom, MultiPolygon):
                polygons = list(sh_geom.geoms)

            depth_band = props.get("depth_band", props.get("layer", "Flood Zone"))
            min_d = props.get("min_depth_m", 0.0)
            max_d = props.get("max_depth_m", 1.0)
            model_name = props.get("model", "Hydrodynamic")

            style_url = "#moderateStyle"
            if min_d >= 3.0:
                style_url = "#catastrophicStyle"
            elif min_d >= 1.5:
                style_url = "#highHazardStyle"
            elif min_d >= 0.5:
                style_url = "#moderateStyle"
            elif model_name == "SPH":
                style_url = "#sphSurgeStyle"
            else:
                style_url = "#mildStyle"

            for p_idx, poly in enumerate(polygons):
                coords_str = " ".join([f"{pt[0]},{pt[1]},0" for pt in poly.exterior.coords])
                placemark = f"""
    <Placemark>
      <name>{depth_band} (Zone {idx+1}.{p_idx+1})</name>
      <styleUrl>{style_url}</styleUrl>
      <description><![CDATA[
        <h3>Hydrodynamic Simulation Layer</h3>
        <p><b>Model:</b> {model_name}</p>
        <p><b>Depth Classification:</b> {depth_band}</p>
        <p><b>Estimated Depth:</b> {min_d}m - {max_d}m</p>
        <p><b>Coordinate System:</b> WGS84 (EPSG:4326)</p>
      ]]></description>
      <Polygon>
        <extrude>1</extrude>
        <altitudeMode>clampToGround</altitudeMode>
        <outerBoundaryIs>
          <LinearRing>
            <coordinates>{coords_str}</coordinates>
          </LinearRing>
        </outerBoundaryIs>
      </Polygon>
    </Placemark>
"""
                kml_body.append(placemark)

        kml_footer = """
  </Document>
</kml>
"""
        full_kml = kml_header + "".join(kml_body) + kml_footer
        with open(out_kml_path, "w", encoding="utf-8") as f:
            f.write(full_kml)

        return out_kml_path

    @staticmethod
    def generate_hadr_executive_report(
        scenario_data: Dict[str, Any],
        base_filename: str = "hadr_situation_report"
    ) -> Path:
        """
        Generates an incident commander HADR situation report.
        """
        out_txt_path = EXPORT_DIR / f"{base_filename}.md"
        basin_name = scenario_data.get("basin_name", "Indian River Basin")
        loss = scenario_data.get("loss_damage", {})
        sph = scenario_data.get("sph_metrics", {})
        delft = scenario_data.get("delft3d_metrics", {})
        infra = scenario_data.get("infrastructure_status", [])

        report = f"""# 🚨 HADR SITUATION REPORT: DAM BREAK & INUNDATION ASSESSMENT
**National Technical Research Organisation (NTRO) / Jal-Drishti Incident Command**
**Basin / Location:** {basin_name}
**Timestamp:** 2026-09-23 | Classification: TACTICAL DISASTER RESPONSE

---

## 1. Executive Summary & Core Hydrodynamic Impact
- **Total Catchment Inundated Area:** {delft.get('total_inundated_area_km2', 0.0)} sq km
- **Near-Field SPH Peak Surge Velocity:** {sph.get('peak_surge_velocity_ms', 0.0)} m/s
- **Peak Dynamic Impact Pressure:** {sph.get('max_dynamic_pressure_kpa', 0.0)} kPa
- **Delft3D Downstream Peak Depth:** {delft.get('peak_depth_m', 0.0)} m
- **Estimated Arrival Window:** {delft.get('wave_arrival_window_min', [0, 0])[0]} to {delft.get('wave_arrival_window_min', [0, 0])[1]} minutes

---

## 2. Humanitarian Loss & Economic Exposure
- **Total Estimated Economic Damage:** ₹ {loss.get('total_economic_loss_inr_crores', 0.0)} Crores
  - Residential Housing Damage: ₹ {loss.get('sectoral_losses_inr_crores', {}).get('residential', 0.0)} Cr
  - Commercial / Industrial Loss: ₹ {loss.get('sectoral_losses_inr_crores', {}).get('commercial_industrial', 0.0)} Cr
  - Agricultural Cropland Loss: ₹ {loss.get('sectoral_losses_inr_crores', {}).get('agricultural', 0.0)} Cr ({loss.get('agricultural_area_submerged_ha', 0.0)} Hectares)
  - Critical Infrastructure Damage: ₹ {loss.get('sectoral_losses_inr_crores', {}).get('public_infrastructure', 0.0)} Cr
- **Population at Immediate Risk:** {loss.get('population_exposed', 0):,} citizens
- **Structures Compromised / Damaged:** {loss.get('buildings_damaged_count', 0):,} units

---

## 3. Critical Infrastructure Threat Matrix
"""
        for item in infra:
            report += f"- **{item['name']}** ({item['type'].upper()}): Status `{item['status']}` | Flood Depth: {item['inundation_depth_m']}m | Action: *{item['urgency_action']}*\n"

        report += """
---

## 4. Evacuation Protocol Recommendations
1. Activate designated Safe Evacuation Corridors immediately. Avoid all low-lying river arterial highways.
2. Direct evacuees toward high-ground Cantonment and Monastic Relief Shelters.
3. Deploy NDRF / SDRF watercraft and aerial airlift units to Critical Danger zones.
"""
        with open(out_txt_path, "w", encoding="utf-8") as f:
            f.write(report)

        return out_txt_path
